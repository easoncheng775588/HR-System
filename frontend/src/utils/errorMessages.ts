type DotPrefix<T extends string> = T extends '' ? '' : `.${T}`;
type LeafPaths<T> = T extends string
  ? ''
  : {
      [K in Extract<keyof T, string>]: `${K}${DotPrefix<LeafPaths<T[K]>>}`
    }[Extract<keyof T, string>];

export type ErrorMessageKey = Exclude<LeafPaths<typeof ErrorMessages>, ''>;

export const getErrorMessage = (key: ErrorMessageKey, ...args: Array<string | number>) => {
  const keys = key.split('.');
  let message: unknown = ErrorMessages;

  for (const k of keys) {
    if (typeof message === 'object' && message !== null && k in (message as Record<string, unknown>)) {
      message = (message as Record<string, unknown>)[k];
    } else {
      return ErrorMessages.common.unknownError;
    }
  }

  if (typeof message === 'string') {
    if (args.length > 0) {
      let i = 0;
      return message.replace(/%[sd]/g, () => String(args[i++] ?? ''));
    }
    return message;
  }

  return ErrorMessages.common.unknownError;
};

export default ErrorMessages;
